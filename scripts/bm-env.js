#!/usr/bin/env node
/**
 * bm-react-native-env: turns a `.env` file into a TypeScript module whose values are XOR-encoded
 * against a fresh random key (the equivalent of Flutter's `envied` with `obfuscate: true`), so the
 * plain text never appears in the JS bundle or in `strings`.
 *
 *   npx bm-react-native-env [--mode staging] [--env .env] [--out src/core/env.g.ts] [--example .env.example] [--name Env]
 *
 * Environments: with a mode (`--mode staging` or `APP_ENV=staging`) the files are layered, later ones
 * overriding earlier ones: `.env`, `.env.staging`, `.env.local`, `.env.staging.local`. Missing layers are
 * skipped. `--env <file>` (or APP_ENV_FILE) reads exactly that one file instead.
 *
 * This is obfuscation, not encryption: the app decodes the values at runtime, so a determined
 * attacker can too. Keep real secrets on a server.
 *
 * Node-only; it is not part of the package's React Native entry point.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

/** Parses `KEY=VALUE` lines (comments, blank lines, single / double quotes, values containing `=`). */
function parse(text) {
  const values = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 1) continue;
    let value = line.slice(eq + 1).trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    values[line.slice(0, eq).trim()] = value;
  }
  return values;
}

/**
 * Writes the generated module.
 * @param {{cwd?: string, mode?: string, env?: string, out?: string, example?: string, name?: string, log?: boolean}} [options]
 * @returns {{keys: string[], source: string, sources: string[], out: string}}
 */
function generate(options = {}) {
  const cwd = options.cwd || process.cwd();
  const example = path.resolve(cwd, options.example || '.env.example');
  const out = path.resolve(cwd, options.out || 'src/core/env.g.ts');
  const name = options.name || 'Env';
  const mode = options.mode || process.env.APP_ENV || '';
  const single = options.env || process.env.APP_ENV_FILE;

  const layers = single
    ? [path.resolve(cwd, single)]
    : ['.env', mode && `.env.${mode}`, '.env.local', mode && `.env.${mode}.local`]
        .filter(Boolean)
        .map((file) => path.resolve(cwd, file));
  const found = layers.filter((file) => fs.existsSync(file));
  const sources = found.length > 0 ? found : [example];
  if (!fs.existsSync(sources[0])) {
    throw new Error(`[bm-env] none of ${layers.map((f) => path.relative(cwd, f)).join(', ')} or ${path.relative(cwd, example)} exists`);
  }
  if (found.length === 0 && options.log !== false) {
    console.warn(`[bm-env] ${path.relative(cwd, layers[0])} not found, using ${path.relative(cwd, example)}`);
  }
  const values = Object.assign({}, ...sources.map((file) => parse(fs.readFileSync(file, 'utf8'))));
  const source = sources.map((file) => path.relative(cwd, file)).join(' + ');

  const entries = Object.entries(values).map(([key, value]) => {
    const data = Buffer.from(value, 'utf8');
    const pad = crypto.randomBytes(Math.max(data.length, 1));
    const encoded = Buffer.from(data.map((byte, i) => byte ^ pad[i]));
    return `  ${key}: reveal([${[...encoded].join(',')}], [${[...pad].join(',')}]),`;
  });

  const body = `// GENERATED by bm-react-native-env from ${source}. Do not edit or commit.
/* eslint-disable */

function reveal(data: number[], key: number[]): string {
  const bytes = data.map((byte, i) => byte ^ key[i]);
  return decodeURIComponent(bytes.map((b) => '%' + b.toString(16).padStart(2, '0')).join(''));
}

export const ${name} = {
${entries.join('\n')}
} as const;
`;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, body);
  return { keys: Object.keys(values), source, sources, out };
}

module.exports = { generate, parse };

if (require.main === module) {
  const args = process.argv.slice(2);
  const options = {};
  for (let i = 0; i < args.length; i += 2) {
    const flag = args[i];
    if (!['--mode', '--env', '--out', '--example', '--name'].includes(flag) || args[i + 1] === undefined) {
      console.error('Usage: bm-react-native-env [--mode staging] [--env .env] [--out src/core/env.g.ts] [--example .env.example] [--name Env]');
      process.exit(2);
    }
    options[flag.slice(2)] = args[i + 1];
  }
  try {
    const { keys, out, source } = generate(options);
    console.log(`[bm-env] wrote ${path.relative(process.cwd(), out)} from ${source} (${keys.join(', ')})`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
